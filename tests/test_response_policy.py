def test_rule_replay_preserves_frozen_answer_and_does_not_generate(tmp_path):
    case = no_answer_case()
    answer = "知识库中没有足够信息回答该问题。年假按自然年度管理。[来源：HR/HR-0]"
    source = {"record_id": "one", "case_id": case.case_id, "variant": "direct", "trial_id": 0,
              "question": case.question, "answerable": False, "reference_answer": None, "answer": answer,
              "context": "the stored context", "run_id": "original", "status": "completed", "rules": {},
              "deterministic_passed": False, "retrieval": [{"content": background().document.page_content,
              "doc_id": "HR", "chunk_id": "HR-0", "score": .9, "rank": 1}]}
    store = RunStore(tmp_path, {"kind": "replay"})
    replay_rules(store, [source], {case.case_id: case})
    replay_rules(store, [source], {case.case_id: case})
    assert len(store.rows()) == 1
    row = store.rows()[0]
    assert row["answer"] == answer and row["source_run_id"] == "original" and row["new_generation"] is False
    assert row["deterministic_passed"] and row["original_deterministic_passed"] is False
    with pytest.raises(ValueError, match="用例定义不同"):
        replay_rules(store, [{**source, "question": "changed"}], {case.case_id: case})
