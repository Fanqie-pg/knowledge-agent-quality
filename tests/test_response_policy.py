def no_answer_case():
    return RetrievalCase("missing", "试用期几个月？", [], None, False, "unanswerable", "easy", [])


def background():
    return RetrievalResult(Document(page_content="年假按自然年度管理。", metadata={"doc_id": "HR", "chunk_id": "HR-0"}), .9, 1)


def test_refusal_may_include_background_but_must_still_refuse():
    answer = "就本次资料而言，知识库中没有足够信息回答该问题。已知年假按自然年度管理。[来源：HR/HR-0]"
    result = evaluate_rag_answer(no_answer_case(), answer, [background()])
    assert result.deterministic_checks_passed and result.rule_version == RAG_RULE_VERSION
    invented_answer = "试用期为3个月。[来源：HR/HR-0]"
    assert not evaluate_rag_answer(no_answer_case(), invented_answer, [background()]).deterministic_checks_passed


def test_optional_background_cannot_cite_unretrieved_source():
    answer = "知识库中没有足够信息回答该问题。年假按自然年度管理。[来源：UNKNOWN/MISSING]"
    result = evaluate_rag_answer(no_answer_case(), answer, [background()])
    assert result.citation_presence_correct and not result.citations_grounded
