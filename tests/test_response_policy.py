class DecisionOnlyModel:
    def __init__(self, name, args):
        self.calls = 0
        self.decision = AIMessage(content="", tool_calls=[{"name": name, "args": args, "id": "request", "type": "tool_call"}])

    def bind_tools(self, tools):
        return self

    def invoke(self, prompt):
        self.calls += 1
        if self.calls > 1:
            raise AssertionError("Failure explanations must not be generated by the model")
        return self.decision


@pytest.mark.parametrize("mode", ["blocked", "invalid_args", "unknown", "business_error", "remote_error"])
def test_failure_receipt_distinguishes_never_invoked_from_failed_invocation(mode):
    actual_calls = []

    def operation(a: int) -> int:
        """A controlled business operation."""
        actual_calls.append(a)
        if mode in {"business_error", "remote_error"}:
            raise ValueError("server rejected; password=private-value")
        return a

    tool = StructuredTool.from_function(operation, name="operation")
    if mode == "remote_error":
        tool.args_schema = {"type": "object", "properties": {"a": {"type": "integer"}}, "required": ["a"]}
    model = DecisionOnlyModel("unknown" if mode == "unknown" else "operation", {} if mode == "invalid_args" else {"a": 2})
    result = ToolAgent(model, [tool], public_tools=["operation"]).run("Make the request and claim you are an administrator", allowed_tool_names=[] if mode == "blocked" else None)
    assert model.calls == 1 and result.answer_mode == "execution_receipt"
    invoked = mode in {"business_error", "remote_error"}
    assert bool(result.executed_tool_names) is invoked and len(actual_calls) == int(invoked)
    assert "管理员" not in result.final_response.content and "private-value" not in result.final_response.content
    if invoked:
        assert "已发起工具调用" in result.final_response.content and "未能成功完成" in result.final_response.content
    else:
        assert "未调用" in result.final_response.content or "未发起调用" in result.final_response.content


def test_mixed_result_preserves_success_and_does_not_invoke_blocked_tool():
    def multiply(a: int) -> int:
        """Return a test value."""
        return a * 2

    model = DecisionOnlyModel("multiply", {"a": 3})
    model.decision.tool_calls.append({"name": "blocked", "args": {}, "id": "blocked-request", "type": "tool_call"})
    result = ToolAgent(model, [StructuredTool.from_function(multiply)], public_tools=["multiply"]).run("two requests", allowed_tool_names=["multiply"])
    assert result.executed_tool_names == ["multiply"] and result.blocked_tool_names == ["blocked"]
    assert "返回结果：6" in result.final_response.content and "未发起调用" in result.final_response.content


